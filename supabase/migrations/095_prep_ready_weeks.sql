-- Буферът преди сцената.
--
-- Кривата на подготовката свършваше в деня на шоуто, тоест разпределяше
-- сваляне и върху пиковата седмица — а през нея не се сваля мазнина. Отгоре
-- източникът иска и поне една седмица готов предварително. И двете се събират
-- в едно число: колко седмици преди шоуто целевото тегло трябва да е взето.
--
-- 2 по подразбиране = пиковата седмица + една седмица готов предварително.
alter table public.prep_protocols
  add column if not exists ready_weeks smallint not null default 2
  check (ready_weeks between 0 and 6);

comment on column public.prep_protocols.ready_weeks is
  'Седмици преди шоуто, в които целевото тегло вече трябва да е взето: пиковата седмица плюс буфер.';
