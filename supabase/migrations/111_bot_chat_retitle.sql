-- 111_bot_chat_retitle.sql
-- Заглавието се прекроява веднъж, след като разговорът покаже за какво е.
--
-- Заглавието е първият въпрос, отрязан на шейсет знака. Това е добро решение
-- за нов разговор: разпознава се по това, с което е започнал, и не иска нищо
-- от човека. Но след третата реплика често вече не описва разговора — питал е
-- „колко ми остава до целта", а разговорът е свършил с това как да си подреди
-- закуската.
--
-- Оттук нататък, когато нишката порасне, заглавието се прекроява веднъж и
-- това се отбелязва. Веднъж, не при всяка реплика: заглавие, което се мени
-- всеки път, е заглавие, по което не може да се търси с памет.

alter table public.bot_chats
  add column if not exists title_auto boolean not null default false;

comment on column public.bot_chats.title_auto is
  'Прекроено ли е вече заглавието от разговора. Става веднъж.';
