-- 108_bot_memory_seen.sql
-- Паметта се учи и от думи, не само от събития.
--
-- Дотук свиването на „научено" се задействаше само когато събитията нараснат с
-- десет. Събитие се пише, когато ботът предложи нещо и човекът го приеме или
-- откаже — тоест паметта учеше единствено от избор между ястия.
--
-- Но най-важното за един човек се казва с думи и веднъж: „не ям риба",
-- „тренирам в шест сутринта", „коляното ме боли при клек". Такова изречение не
-- вдига нито един брояч и досега не влизаше в паметта никога — човекът го
-- казваше, ботът отговаряше съобразително в същия разговор, а на следващия
-- ден питаше отново.
--
-- Оттук нататък и репликите се броят, със свой праг.

alter table public.bot_profile
  add column if not exists messages_seen int not null default 0;

comment on column public.bot_profile.messages_seen is
  'Колко реплики са влезли в последното свиване на научено.';
