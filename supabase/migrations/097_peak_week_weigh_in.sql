-- Кантарът.
--
-- При категория с таван пиковата седмица има два крайни срока, не един, и
-- обвързващият е първият. Зареждането качва два-три килограма за три дни —
-- ако то върви преди претеглянето, човек прави тегло с натъпкан стомах или
-- изобщо не го прави. Затова при обявен кантар зареждането тръгва след него.
--
-- Часовете между кантара и сцената решават колко изобщо може да се вкара:
-- кантар в събота 8:00 при сцена в неделя 11:00 е двайсет и седем часа, а
-- кантар в неделя 8:00 при същата сцена е три. Дните не стигат за тази сметка,
-- затова се пази и час.
alter table public.peak_weeks
  add column if not exists weigh_in_date date,
  add column if not exists weigh_in_time time,
  add column if not exists show_time     time;

comment on column public.peak_weeks.weigh_in_date is
  'Ден на претеглянето. Null значи категория без кантар.';
