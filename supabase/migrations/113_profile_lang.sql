-- 113_profile_lang.sql
-- Езикът на човека стига до сървъра.
--
-- Дотук изборът между български и английски живееше само в браузъра
-- (`localStorage`), защото само приложението го ползваше. Ботът обаче вече
-- говори и сам: нощната обиколка отваря разговор, без някой да я е питал, и
-- няма кого да пита на какъв език да го напише.
--
-- Затова изборът се и записва. Не като настройка с екран — тя си остава в
-- Профил — а като отражение на вече направения избор.

alter table public.profiles
  add column if not exists lang text
  check (lang in ('bg', 'en'));

comment on column public.profiles.lang is
  'На какъв език говори приложението на този човек. Пише се от приложението при смяна; чете се от функциите, които пишат сами.';
