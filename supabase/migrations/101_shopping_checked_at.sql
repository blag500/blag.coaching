-- 101_shopping_checked_at.sql — Кога е купено.
--
-- Списъкът пазеше дали един артикул е отметнат, но не и кога. Това стига за
-- списък, който се изпразва и започва наново; не стига за календар, защото
-- „какво съм купил на 3 септември" няма откъде да се отговори.
--
-- Отметката и часът ѝ вървят заедно: снема ли се отметката, часът пада с нея.
-- Ред, който твърди „купено", без да знае кога, е по-лош от ред, който мълчи.

alter table public.shopping_items
  add column if not exists checked_at timestamptz;

-- Календарът пита „кои артикули са отметнати в този месец". Частичен индекс,
-- защото неотметнатите — които са мнозинството в един жив списък — не се
-- търсят никога по този въпрос.
create index if not exists shopping_items_checked_at_idx
  on public.shopping_items (checked_at)
  where checked_at is not null;

