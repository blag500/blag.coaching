/**
 * Въпросите, които мрежата не е поела.
 *
 * Питането минава през крайна функция, а не през таблица — значи общата опашка
 * (`lib/outbox.js`) не го поема: тя знае да пише редове, не да вика функции.
 * А въпросът към бота се задава точно там, където сигнал няма: сутеренът на
 * залата, магазинът, асансьорът. Дотук отговорът беше „нещо се обърка" и
 * въпросът се губеше — човекът го пише втори път или не го пише.
 *
 * Оттук нататък въпросът остава в разговора със знак, че чака, и заминава при
 * връщане на мрежата. Отговорът влиза в базата от самата функция, така че се
 * появява в нишката дори питането да е заминало, докато разговорът е затворен.
 *
 * localStorage по същата причина като опашката за редовете: няколко стотин
 * байта, четени наведнъж и писани рядко.
 */

const KEY = 'blag_bot_queue'

function read() {
  try { return JSON.parse(localStorage.getItem(KEY) || '[]') }
  catch { return [] }
}

function write(list) {
  try { localStorage.setItem(KEY, JSON.stringify(list)) }
  catch { /* частен режим — опашката живее до затваряне */ }
}

/** Какво чака. Най-старото първо: редът на въпросите е част от разговора. */
export function queued() { return read() }

/** Слага въпрос на опашката. `msgId` е редът на екрана, за да се намери после. */
export function enqueueQuestion({ chatId, question, msgId }) {
  const list = read()
  /* Двайсет е повече, отколкото някой ще натрупа без мрежа. Над това по-старите
     падат: опашка, която расте без край, е опашка, която няма да замине. */
  write([...list, { chatId, question, msgId }].slice(-20))
}

export function dropQuestion(msgId) {
  write(read().filter(q => q.msgId !== msgId))
}
