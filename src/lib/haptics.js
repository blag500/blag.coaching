/* Допирът.
 *
 * Приложението вибрираше на три места в целия код: при смяна на таб, при
 * отмятане на навик и в края на почивката между сериите. Навсякъде другаде —
 * налята вода, приета добавка, вписана храна, взето постижение — пръстът
 * натискаше стъкло и не получаваше нищо обратно.
 *
 * Вибрацията не е украса: тя е единственото, което казва „чух те", преди
 * екранът да е успял да се пренарисува. При бързо тапване — шест капки вода
 * една след друга — тя е разликата между „работи" и „дали натиснах".
 *
 * Един речник, а не число на място на употреба. Числата, писани поотделно,
 * се разминават: 10 тук, 180 там, и после никой не помни кое какво значи.
 * Тук всяко има име, и името казва какво е събитието, а не колко милисекунди
 * трае.
 *
 * Обхват: navigator.vibrate работи на Android (Chrome, Samsung Internet,
 * Firefox). iOS Safari не го поддържа — нито в браузър, нито като PWA от
 * началния екран — така че на iPhone всичко тук е тиха операция без ефект.
 * Това не е причина да го няма: половината клиенти са на Android и за тях
 * това е най-осезаемата разлика в целия интерфейс.
 */

/* Скалата. Всичко под ~10ms се усеща като почукване, ~20ms като натиск,
   а поредица с паузи — като събитие с начало и край.

   Дългите фигури са за неща, които се случват веднъж на ден. Едно почукване
   е за неща, които се случват петдесет пъти. */
const PATTERNS = {
  /* Натиснат бутон. Възможно най-лекото — иначе телефонът бръмчи цял ден. */
  tap:       8,
  /* Превключено състояние: чип, отметка, капка вода. Малко по-плътно от tap,
     защото нещо се е променило, а не само е било натиснато. */
  toggle:    12,
  /* Смяна на раздел. По-леко от превключване — навигацията не е постижение. */
  nav:       6,
  /* Отказ: празно поле, невалидна стойност, изчерпано количество. Две къси
     — двойното почукване е универсалното „не". */
  reject:    [0, 18, 70, 18],
  /* Попадение: макрос вътре в лентата, изпълнена норма вода, завършена
     серия. Плътно и единично — резултат, не аларма. */
  success:   [0, 14, 45, 26],
  /* Денят е затворен: значка, идеален ден, всички навици. Единственото, което
     си позволява три удара. */
  celebrate: [0, 16, 55, 16, 55, 34],
  /* Край на почивката между сериите. Аларма — трябва да се усети през плата
     на джоба, докато телефонът лежи на пейката. */
  alarm:     180,
}

/* Прочетено веднъж и държано в модула. Всяко тапване чете localStorage иначе,
   а localStorage е синхронен: при бърза серия отметки това е четене на диск
   вътре в обработчика на събитието. */
let enabled = (() => {
  try { return localStorage.getItem('blag_haptics') !== '0' } catch { return true }
})()

export function setHapticsEnabled(on) {
  enabled = !!on
  try { localStorage.setItem('blag_haptics', on ? '1' : '0') } catch { /* частен режим */ }
}

export function hapticsEnabled() { return enabled }

/**
 * Един удар по избраното име.
 *
 * Нарочно не хвърля и не връща нищо: това е ефект отстрани на едно
 * взаимодействие, и ако телефонът не може да вибрира, взаимодействието
 * продължава да е валидно. Извиква се направо в обработчика — не в useEffect
 * след това — защото някои браузъри искат вибрацията да е вътре в жеста.
 */
export function haptic(kind = 'tap') {
  if (!enabled) return
  const pattern = PATTERNS[kind]
  if (pattern === undefined) return
  try { navigator.vibrate?.(pattern) } catch { /* отказано от системата */ }
}
