import { supabase } from './supabase'

/**
 * Публикува постижение във фийда.
 *
 * Извиква се от мястото, където събитието се случва — не от фийда, който
 * няма как да знае, че някой е приключил тренировка в друг таб.
 *
 * Мълчи при неуспех нарочно. Това е странична последица от нещо друго:
 * човекът е маркирал тренировката си за завършена и това вече е записано.
 * Ако споделянето не мине — защото връзката е паднала или защото денят вече
 * е публикуван от другия му телефон — той не бива да види грешка за нещо,
 * което не е искал изрично.
 *
 * Повторенията ги спира уникалният индекс posts_one_per_day (миграция 089),
 * а не проверка тук: проверка преди вписване има прозорец между двете, а
 * индексът няма.
 */
export async function shareAchievement(userId, { kind, meta = null, date }) {
  if (!userId || !kind) return
  const logDate = date || new Date().toISOString().slice(0, 10)
  await supabase
    .from('posts')
    .insert({ user_id: userId, kind, meta, log_date: logDate })
}
