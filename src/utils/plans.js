/**
 * Кой е с треньор.
 *
 * Проверката стоеше написана на две места — в App и в Тренировка — и от нея
 * зависи кой може да пренапише плана си. Две копия на такова правило се
 * разминават тихо: единият екран решава едно, другият друго, и никой не
 * забелязва, докато клиент не изтрие плана, който треньорът му е писал.
 *
 * PRO е спрян. Редовете обаче остават: хора, които вече са с plan='pro',
 * трябва да продължат да се броят за с треньор — иначе в деня, в който го
 * махнем, всички те стават самостоятелни и получават право да пренапишат
 * чужда работа. Затова старата стойност се разпознава тук и никъде другаде.
 */
export const LEGACY_COACHED = 'pro'

export function isCoached(profile) {
  const plan = profile?.plan
  return plan === 'coaching' || plan === LEGACY_COACHED
}
